function resolveStatus(stock: number, minStock: number): Product["status"] {
  if (stock <= 0) return "sin_stock";
  if (stock <= Math.ceil(minStock * 0.5)) return "critico";
  if (stock <= minStock) return "bajo";
  return "normal";
}

